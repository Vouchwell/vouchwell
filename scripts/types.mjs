#!/usr/bin/env node
/**
 * TypeScript declarations for the npm packages, generated from their JSDoc.
 *
 *     npm run types               regenerate packages/<name>/types/
 *     npm run types -- --check    fail if the committed declarations are out
 *                                 of date, then type-check a consumer of them
 *
 * The packages stay plain JavaScript, with no build step and no dependencies.
 * TypeScript is only needed to write the declarations, so it is not a
 * devDependency: this installs one pinned version, with @types/node, into a
 * cache directory outside the repository, and `npm install` still fetches
 * nothing. The declarations are committed, reviewed in diffs and published as
 * they are.
 */

import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

// Pinned: a different TypeScript can word the same declarations differently,
// and --check compares them byte for byte.
const TYPESCRIPT = '7.0.2';
const TYPES_NODE = '22.20.5';

/**
 * The libraries, in dependency order: each one's declarations are read when
 * the next is generated. The CLI has nothing to import, so it has none.
 */
export const PACKAGES = ['core', 'proxy', 'dashboard', 'server'];

const HEADER = '// Generated by scripts/types.mjs from the JSDoc in src/. Do not edit: run `npm run types`.\n';

/** Install the pinned TypeScript once, outside the repository. */
function tooling() {
  const dir = path.join(os.tmpdir(), `vouchwell-types-ts${TYPESCRIPT}-node${TYPES_NODE}`);
  const tsc = path.join(dir, 'node_modules', 'typescript', 'bin', 'tsc');
  if (!fs.existsSync(tsc)) {
    fs.mkdirSync(dir, { recursive: true });
    const res = spawnSync(
      'npm',
      ['install', '--prefix', dir, '--no-save', '--no-audit', '--no-fund', '--ignore-scripts', `typescript@${TYPESCRIPT}`, `@types/node@${TYPES_NODE}`],
      { stdio: 'inherit', shell: process.platform === 'win32' },
    );
    if (res.status !== 0 || !fs.existsSync(tsc)) throw new Error(`could not install typescript@${TYPESCRIPT}`);
  }
  return { tsc, typeRoot: path.join(dir, 'node_modules', '@types') };
}

/**
 * Run tsc with a config built here, so no tsconfig in the repository can be
 * mistaken for a build step.
 *
 * @param {{ tsc: string, typeRoot: string }} tool
 * @param {Record<string, unknown>} compilerOptions
 * @param {string[]} include
 */
function tsc(tool, compilerOptions, include) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'vouchwell-tsconfig-'));
  const config = path.join(dir, 'tsconfig.json');
  fs.writeFileSync(config, JSON.stringify({
    compilerOptions: {
      module: 'nodenext',
      moduleResolution: 'nodenext',
      target: 'es2022',
      strict: true,
      skipLibCheck: true,
      newLine: 'lf',
      typeRoots: [tool.typeRoot],
      types: ['node'],
      ...compilerOptions,
    },
    include,
  }, null, 2));
  try {
    const res = spawnSync(process.execPath, [tool.tsc, '-p', config], { encoding: 'utf8' });
    return { ok: res.status === 0, output: `${res.stdout}${res.stderr}`.trim() };
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
}

/**
 * Write one package's declarations into `outDir`, replacing what was there.
 *
 * @param {{ tsc: string, typeRoot: string }} tool
 * @param {string} pkg
 * @param {string} outDir
 */
function emit(tool, pkg, outDir) {
  const src = path.join(ROOT, 'packages', pkg, 'src');
  fs.rmSync(outDir, { recursive: true, force: true });
  const res = tsc(tool, {
    allowJs: true,
    checkJs: false,
    declaration: true,
    emitDeclarationOnly: true,
    rootDir: src,
    outDir,
  }, [path.join(src, '**', '*.js')]);
  if (!res.ok) throw new Error(`tsc failed for packages/${pkg}:\n${res.output}`);
  for (const file of listFiles(outDir)) {
    const full = path.join(outDir, file);
    // tsc carries a bin's `#!` line into its declaration, where it means
    // nothing, and below the header it would be a syntax error.
    const body = fs.readFileSync(full, 'utf8').replace(/^#![^\n]*\n/, '');
    fs.writeFileSync(full, HEADER + body);
  }
}

/** @param {string} dir  Files under `dir`, relative and sorted, with forward slashes. */
function listFiles(dir) {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir, { recursive: true, withFileTypes: true })
    .filter((e) => e.isFile())
    .map((e) => path.relative(dir, path.join(e.parentPath ?? e.path, e.name)).split(path.sep).join('/'))
    .sort();
}

/**
 * The differences between two directories of declarations, as messages.
 *
 * @param {string} committed
 * @param {string} fresh
 * @param {string} label
 */
export function staleFiles(committed, fresh, label) {
  const have = listFiles(committed);
  const want = listFiles(fresh);
  const problems = [];
  for (const f of want) {
    if (!have.includes(f)) problems.push(`${label}/${f} is missing`);
    else if (fs.readFileSync(path.join(committed, f), 'utf8') !== fs.readFileSync(path.join(fresh, f), 'utf8')) {
      problems.push(`${label}/${f} is out of date`);
    }
  }
  for (const f of have) if (!want.includes(f)) problems.push(`${label}/${f} is no longer generated`);
  return problems;
}

function main() {
  const check = process.argv.includes('--check');
  const tool = tooling();

  if (!check) {
    for (const pkg of PACKAGES) {
      emit(tool, pkg, path.join(ROOT, 'packages', pkg, 'types'));
      console.log(`wrote packages/${pkg}/types/`);
    }
    return 0;
  }

  // Generate into a scratch directory and compare. Each package after core
  // resolves its dependencies' committed declarations, which this same check
  // has just compared, in order.
  const scratch = fs.mkdtempSync(path.join(os.tmpdir(), 'vouchwell-types-check-'));
  const problems = [];
  try {
    for (const pkg of PACKAGES) {
      const fresh = path.join(scratch, pkg);
      emit(tool, pkg, fresh);
      problems.push(...staleFiles(path.join(ROOT, 'packages', pkg, 'types'), fresh, `packages/${pkg}/types`));
    }
  } finally {
    fs.rmSync(scratch, { recursive: true, force: true });
  }
  if (problems.length) {
    for (const p of problems) console.error(`✗ ${p}`);
    console.error('\nRun `npm run types` and commit packages/*/types.');
    return 1;
  }
  console.log(`✓ declarations are up to date (typescript ${TYPESCRIPT})`);

  // A consumer, resolving the packages through their package.json the way an
  // npm install would. Its @ts-expect-error lines fail if a type is `any`.
  // Every declaration file is checked with it, skipLibCheck off, so one no
  // entry point imports (a bin's) cannot ship broken unnoticed.
  const consumer = tsc(tool, { noEmit: true, skipLibCheck: false }, [
    path.join(ROOT, 'scripts', 'types-consumer.ts'),
    ...PACKAGES.map((pkg) => path.join(ROOT, 'packages', pkg, 'types', '**', '*.d.ts')),
  ]);
  if (!consumer.ok) {
    console.error(`✗ the declarations, or scripts/types-consumer.ts against them, do not type-check:\n${consumer.output}`);
    return 1;
  }
  console.log('✓ every declaration type-checks, and so does a consumer of them');
  return 0;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    process.exitCode = main();
  } catch (e) {
    console.error(`✗ ${/** @type {Error} */ (e).message}`);
    process.exitCode = 1;
  }
}
